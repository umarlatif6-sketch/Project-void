def seed_patent_drafts_into_chronicle() -> None:
    """
    Seed the three priority PATENT_DRAFT entries into the Adriana Chronicle.
    Idempotent — will not duplicate entries.
    """
    try:
        from void_engine.chronicle_adriana import _get_db, _ensure_seed_capture_columns
        from void_engine.al_jabr_286 import fatiha_286_hexdigest_from_str
        conn = _get_db()
        try:
            cur = conn.cursor()
            _ensure_seed_capture_columns(cur)
            current_season = _get_current_season_safe()
            seeded = 0
            for i, claim in enumerate(_PRE_GENERATED_CLAIMS):
                cur.execute(
                    "SELECT id FROM chronicle_entries WHERE title = %s AND entry_type = %s LIMIT 1",
                    (claim["title"], "PATENT_DRAFT"),
                )
                if cur.fetchone():
                    continue
                body = _build_claim_body(claim)
                al_jabr_hash = fatiha_286_hexdigest_from_str(f"PATENT_DRAFT|{claim['short_id']}|{claim['title']}")
                cur.execute(
                    """INSERT INTO chronicle_entries
                       (chapter_number, title, subtitle, glyph_sequence, body_text, al_jabr_hash, entry_type, season)
                       VALUES (%s, %s, %s, %s, %s, %s, 'PATENT_DRAFT', %s)""",
                    (
                        9 + i,
                        claim["title"],
                        f"{claim['short_id']} — UK Biomedical Meeting Draft",
                        claim["glyph_sequence"],
                        body,
                        al_jabr_hash,
                        current_season,
                    ),
                )
                seeded += 1
            conn.commit()
            if seeded:
                logger.info("Seeded %d PATENT_DRAFT entries into Chronicle", seeded)
        finally:
            conn.close()
    except Exception as e:
        logger.warning("Patent draft seeding failed: %s", e)


