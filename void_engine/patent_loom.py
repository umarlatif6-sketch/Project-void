def _build_claim_body(claim: Dict) -> str:
    return (
        f"[PATENT_DRAFT] {claim['short_id']}\n\n"
        f"--- TECHNICAL NOVELTY ---\n{claim['novelty']}\n\n"
        f"--- INDUSTRIAL APPLICABILITY ---\n{claim['applicability']}\n\n"
        f"--- SOVEREIGN ENCRYPTION ---\n{claim['encryption']}"
    )


def process_forge_text(text: str) -> Dict:
    """
    Process a block of technical forge text into three-layer patent language.

    Returns:
        {
          "novelty":        str,
          "applicability":  str,
          "encryption":     str,
          "draft_claim":    str,   # formatted full claim
          "claim_id":       str,
        }
    """
    if not text or not text.strip():
        return {"error": "No text provided"}

    text = text.strip()
    word_count = len(text.split())

    claim_id = _generate_claim_id(text)

    novelty = _extract_novelty(text)
    applicability = _extract_applicability(text)
    encryption = _build_encryption_layer(text)

    draft_claim = (
        f"DRAFT PATENT CLAIM [{claim_id}]\n\n"
        f"1. (Technical Novelty)\n   {novelty}\n\n"
        f"2. (Industrial Applicability)\n   {applicability}\n\n"
        f"3. (Sovereign Encryption)\n   {encryption}"
    )

    return {
        "claim_id":       claim_id,
        "source_length":  word_count,
        "novelty":        novelty,
        "applicability":  applicability,
        "encryption":     encryption,
        "draft_claim":    draft_claim,
        "generated_at":   datetime.now(timezone.utc).isoformat(),
    }


def _extract_novelty(text: str) -> str:
    """Derive a Technical Novelty sentence from forge text."""
    keywords = {
        "piezoelectric": "piezoelectric signal transduction in biological fibre arrays",
        "mycelium": "mycelial impedance as a dynamic bio-electrical conductor",
        "silk": "silk-fibre mesh as a resonant signal conduit",
        "neural": "non-invasive neural-state capture via capacitive bio-electric coupling",
        "resonan": "resonance-frequency anchored data transmission at 432 Hz",
        "steganograph": "steganographic concealment of sensitive data within natural-signal carriers",
        "hash": "sovereign 286-bit hashing with verse-weight extension invisible to standard scanners",
        "aquaponics": "aquaponic bio-sensor integration with sovereign data pipelines",
        "flywheel": "kinetic flywheel energy storage coupled to biological monitoring systems",
        "compress": "adaptive dual-compression for biological payload steganography",
    }

    text_lower = text.lower()
    found = [desc for kw, desc in keywords.items() if kw in text_lower]

    if found:
        primary = found[0]
        secondary = f", in combination with {found[1]}" if len(found) > 1 else ""
        return (
            f"A method and apparatus employing {primary}{secondary}, "
            f"wherein said system produces a novel technical outcome not "
            f"disclosed or anticipated in prior art as of April 2026."
        )

    sentences = [s.strip() for s in re.split(r'[.!?]', text) if len(s.strip()) > 40]
    core = sentences[0] if sentences else text[:200]
    return (
        f"A novel system comprising: {core[:200].rstrip(',;')}; "
        f"wherein said combination produces a technical effect not previously "
        f"disclosed in the prior art."
    )


