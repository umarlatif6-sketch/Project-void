def get_all_cards():
    return CARDS


def get_cards_by_module(module_id):
    if module_id not in MODULES:
        return []
    return [c for c in CARDS if c["module"] == module_id]


def get_card_by_id(card_id):
    for c in CARDS:
        if c["id"] == card_id:
            return c
    return None


def get_module_stats():
    stats = {}
    for mod in MODULES:
        cards = get_cards_by_module(mod)
        stats[mod] = {
            "name": MODULE_NAMES[mod],
            "count": len(cards),
        }
    return stats
